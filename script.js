// Contact form submit
const form = document.getElementById('contact-form');
if (form) {
  const statusEl = document.getElementById('form-status');
  // Preselect topic from link clicks or URL
  const topicSelect = form.querySelector('select[name="topic"]');
  const preset = params.get('topic');
  if (topicSelect && preset) {
    Array.from(topicSelect.options).forEach((o) => {
      if (o.text.toLowerCase().includes(preset.toLowerCase())) topicSelect.value = o.value;
    });
  }
  document.querySelectorAll('[data-topic]').forEach((el) => {
    el.addEventListener('click', () => {
      const t = el.getAttribute('data-topic');
      if (topicSelect && t) topicSelect.value = t;
    });
  });
  form.addEventListener('submit', async (e) => {
    e.preventDefault();
    statusEl.textContent = '';
    // Use native validation UI
    if (!form.reportValidity()) return;

    const fd = new FormData(form);
    if (fd.get('website')) return; // honeypot

    // File size guard: total <= 10MB
    const fileInput = form.querySelector('input[type="file"][name="files"]');
    if (fileInput && fileInput.files && fileInput.files.length) {
      let total = 0;
      for (const f of fileInput.files) total += f.size || 0;
      if (total > 10 * 1024 * 1024) {
        statusEl.textContent = getText('contact.form.tooLarge', 'Taille totale des fichiers > 10 Mo.');
        return;
      }
    }

    const btn = form.querySelector('button[type="submit"]');
    btn.disabled = true;
    btn.textContent = getText('contact.form.sending', 'Envoi...');
    try {
      const action = form.getAttribute('action');
      if (!action) {
        statusEl.textContent = getText(
          'contact.form.unconfigured',
          'Formulaire non configuré: ajoutez un endpoint (Formspree/Getform).'
        );
        return;
      }
      const res = await fetch(action, {
        method: 'POST',
        body: fd,
        headers: { Accept: 'application/json' }
      });
      let ok = res.ok;
      let out = {};
      try {
        out = await res.json();
      } catch (err) {
        // ignore JSON parsing error
      }
      if (ok || out.ok) {
        statusEl.textContent = getText('contact.form.success', 'Merci, votre message a été envoyé.');
        form.reset();
      } else {
        statusEl.textContent =
          (out && (out.error || out.message)) ||
          getText('contact.form.error', 'Une erreur est survenue. Réessayez.');
      }
    } catch (err) {
      statusEl.textContent = getText('contact.form.network', 'Erreur réseau. Vérifiez votre connexion.');
    } finally {
      btn.disabled = false;
      btn.textContent = getText('contact.form.submit', 'Envoyer');
    }
  });
}
