let params = new URLSearchParams(window.location.search);
const supportedLangs = Object.keys(translations);
const storageKey = 'taolenn-lang';

const readStoredLang = () => {
  try {
    return window.localStorage ? window.localStorage.getItem(storageKey) : null;
  } catch (err) {
    return null;
  }
};

const persistLang = (lang) => {
  try {
    if (window.localStorage) window.localStorage.setItem(storageKey, lang);
  } catch (err) {
    // Ignore storage errors (private mode, disabled storage…)
  }
};

let currentLang = params.get('lang') || readStoredLang() || 'fr';
if (!supportedLangs.includes(currentLang)) currentLang = 'fr';

const getText = (key, fallback = '') => {
  const active = translations[currentLang] || translations.fr;
  if (active && key in active) return active[key];
  if (translations.fr && key in translations.fr) return translations.fr[key];
  return fallback;
};

const applyLanguage = (lang) => {
  const dict = translations[lang] || translations.fr;
  const html = document.documentElement;
  html.lang = lang === 'zh' ? 'zh-Hans' : lang;
  html.setAttribute('data-lang', lang);

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (!key || !(key in dict)) return;
    const attr = el.getAttribute('data-i18n-attr');
    const value = dict[key];
    if (attr) {
      el.setAttribute(attr, value);
    } else {
      el.innerHTML = value;
    }
  });
};

applyLanguage(currentLang);

const langRadios = document.querySelectorAll('input[name="lang"]');
langRadios.forEach((radio) => {
  radio.checked = radio.value === currentLang;
  radio.addEventListener('change', () => {
    if (!radio.checked || !supportedLangs.includes(radio.value)) return;
    currentLang = radio.value;
    applyLanguage(currentLang);
    persistLang(currentLang);
    try {
      const url = new URL(window.location.href);
      url.searchParams.set('lang', currentLang);
      window.history.replaceState({}, '', url);
      params = new URLSearchParams(window.location.search);
    } catch (err) {
      // Ignore history errors (older browsers)
    }
  });
});

